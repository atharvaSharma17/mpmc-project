ORG 0000H
LJMP START

ORG 000BH
LJMP TIMER0_ISR

;-----------------------------------
START:
    MOV P1,#0FFH

    CLR P3.7
    CLR P3.6
    CLR P3.5

    MOV R0,#05H
    MOV R1,#05H
    MOV R2,#05H

    MOV 30H,#00H
    MOV 31H,#00H
    MOV 32H,#00H

    MOV 40H,#00H

; LCD INIT
    MOV A,#38H
    ACALL COMMAND
    ACALL INIT_DELAY

    MOV A,#0CH
    ACALL COMMAND
    ACALL INIT_DELAY

    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY

    MOV A,#06H
    ACALL COMMAND
    ACALL INIT_DELAY

    ACALL TIMER0_INIT
    ACALL SHOW_WELCOME
    ACALL LONG_DELAY

;-----------------------------------
MAIN_LOOP:

CHECK_A:
    JNB P1.3,A_GO
    LJMP CHECK_B

A_GO:
    ACALL DEBOUNCE
    JB P1.3,A_SKIP
    ACALL DISPENSE_A
    SJMP WAIT_A

A_SKIP:
    LJMP CHECK_B

WAIT_A:
    JNB P1.3,WAIT_A
    LJMP MAIN_LOOP

CHECK_B:
    JNB P1.4,B_GO
    LJMP CHECK_C

B_GO:
    ACALL DEBOUNCE
    JB P1.4,B_SKIP
    ACALL DISPENSE_B
    SJMP WAIT_B

B_SKIP:
    LJMP CHECK_C

WAIT_B:
    JNB P1.4,WAIT_B
    LJMP MAIN_LOOP

CHECK_C:
    JNB P1.5,C_GO
    LJMP CHECK_STOCK

C_GO:
    ACALL DEBOUNCE
    JB P1.5,C_SKIP
    ACALL DISPENSE_C
    SJMP WAIT_C

C_SKIP:
    LJMP CHECK_STOCK

WAIT_C:
    JNB P1.5,WAIT_C
    LJMP MAIN_LOOP

CHECK_STOCK:
    JNB P1.6,S_GO
    LJMP CHECK_RESET

S_GO:
    ACALL DEBOUNCE
    JB P1.6,S_SKIP
    ACALL SHOW_STOCK
    SJMP WAIT_S

S_SKIP:
    LJMP CHECK_RESET

WAIT_S:
    JNB P1.6,WAIT_S
    LJMP MAIN_LOOP

CHECK_RESET:
    JNB P1.7,RESET_GO
    LJMP MAIN_LOOP

RESET_GO:
    ACALL DEBOUNCE
    JB P1.7,R_SKIP
    LJMP START

R_SKIP:
    LJMP MAIN_LOOP

;-----------------------------------
DISPENSE_A:
    MOV A,30H
    JZ DA_NEXT
    LJMP MSG_WAIT

DA_NEXT:
    MOV A,R0
    JZ DA_EMPTY
    DEC R0
    MOV 30H,#60
    ACALL MSG_A
    RET

DA_EMPTY:
    LJMP MSG_EMPTY

DISPENSE_B:
    MOV A,31H
    JZ DB_NEXT
    LJMP MSG_WAIT

DB_NEXT:
    MOV A,R1
    JZ DB_EMPTY
    DEC R1
    MOV 31H,#60
    ACALL MSG_B
    RET

DB_EMPTY:
    LJMP MSG_EMPTY

DISPENSE_C:
    MOV A,32H
    JZ DC_NEXT
    LJMP MSG_WAIT

DC_NEXT:
    MOV A,R2
    JZ DC_EMPTY
    DEC R2
    MOV 32H,#60
    ACALL MSG_C
    RET

DC_EMPTY:
    LJMP MSG_EMPTY

;-----------------------------------
SHOW_STOCK:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY

    MOV A,#80H
    ACALL COMMAND

    MOV A,#'A'
    ACALL SEND_DATA
    MOV A,#':'
    ACALL SEND_DATA
    MOV A,R0
    ADD A,#30H
    ACALL SEND_DATA

    MOV A,#' '
    ACALL SEND_DATA

    MOV A,#'B'
    ACALL SEND_DATA
    MOV A,#':'
    ACALL SEND_DATA
    MOV A,R1
    ADD A,#30H
    ACALL SEND_DATA

    MOV A,#0C0H
    ACALL COMMAND

    MOV A,#'C'
    ACALL SEND_DATA
    MOV A,#':'
    ACALL SEND_DATA
    MOV A,R2
    ADD A,#30H
    ACALL SEND_DATA

    ACALL LONG_DELAY
    RET

;-----------------------------------
SHOW_WELCOME:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY

    MOV A,#80H
    ACALL COMMAND
    MOV A,#'I'
    ACALL SEND_DATA
    MOV A,#'C'
    ACALL SEND_DATA
    MOV A,#'U'
    ACALL SEND_DATA

    MOV A,#0C0H
    ACALL COMMAND
    MOV A,#'R'
    ACALL SEND_DATA
    MOV A,#'E'
    ACALL SEND_DATA
    MOV A,#'A'
    ACALL SEND_DATA
    MOV A,#'D'
    ACALL SEND_DATA
    MOV A,#'Y'
    ACALL SEND_DATA
    RET

;-----------------------------------
MSG_A:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY
    MOV A,#'A'
    ACALL SEND_DATA
    RET

MSG_B:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY
    MOV A,#'B'
    ACALL SEND_DATA
    RET

MSG_C:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY
    MOV A,#'C'
    ACALL SEND_DATA
    RET

MSG_WAIT:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY
    MOV A,#'W'
    ACALL SEND_DATA
    RET

MSG_EMPTY:
    MOV A,#01H
    ACALL COMMAND
    ACALL CLEAR_DELAY
    MOV A,#'E'
    ACALL SEND_DATA
    RET

;-----------------------------------
TIMER0_INIT:
    MOV TMOD,#01H
    MOV TH0,#0FCH
    MOV TL0,#066H
    SETB ET0
    SETB EA
    SETB TR0
    RET

;-----------------------------------
TIMER0_ISR:
    MOV TH0,#0FCH
    MOV TL0,#066H

    INC 40H
    MOV A,40H
    CJNE A,#250,EXIT_ISR

    MOV 40H,#00

    MOV A,30H
    JZ SKA
    DEC 30H
SKA:

    MOV A,31H
    JZ SKB
    DEC 31H
SKB:

    MOV A,32H
    JZ SKC
    DEC 32H
SKC:

; LED CONTROL

    MOV A,30H
    JZ LA_OFF
    SETB P3.7
    SJMP LB_CHK
LA_OFF:
    CLR P3.7

LB_CHK:
    MOV A,31H
    JZ LB_OFF
    SETB P3.6
    SJMP LC_CHK
LB_OFF:
    CLR P3.6

LC_CHK:
    MOV A,32H
    JZ LC_OFF
    SETB P3.5
    SJMP EXIT_ISR
LC_OFF:
    CLR P3.5

EXIT_ISR:
    RETI

;-----------------------------------
COMMAND:
    MOV P2,A
    CLR P1.0
    SETB P1.2
    NOP
    NOP
    CLR P1.2
    ACALL SHORT_DELAY
    RET

SEND_DATA:
    MOV P2,A
    SETB P1.0
    SETB P1.2
    NOP
    NOP
    CLR P1.2
    ACALL SHORT_DELAY
    RET

;-----------------------------------
SHORT_DELAY:
    MOV R7,#20
SD1: DJNZ R7,SD1
    RET

LONG_DELAY:
    MOV R7,#200
LD1: MOV R6,#255
LD2: DJNZ R6,LD2
    DJNZ R7,LD1
    RET

CLEAR_DELAY:
    MOV R7,#50
CD1: MOV R6,#255
CD2: DJNZ R6,CD2
    DJNZ R7,CD1
    RET

INIT_DELAY:
    MOV R7,#10
ID1: MOV R6,#255
ID2: DJNZ R6,ID2
    DJNZ R7,ID1
    RET

DEBOUNCE:
    MOV R7,#200
DB1: DJNZ R7,DB1
    RET

END 
